"""Label-free selectors and evaluator-only metrics for protocol v2.

Pure stdlib so budget/metric correctness can be tested without model access.
No fake embeddings or fabricated results are generated by this module.
"""
import math
import random
import statistics
from sampling import changed, uniform

METHODS = ('uniform', 'change', 'scene', 'hybrid', 'hierarchical')
BASELINES = METHODS[:-1]


def static_selection(method, changes, budget):
    n = len(changes)
    budget = min(budget, n)
    if n < 1 or budget < 1:
        return []
    if method == 'uniform':
        return uniform(n, budget)
    if method == 'change':
        return changed(changes, budget)
    if method == 'hybrid':
        selected = uniform(n, max(1, budget // 2))
        for i in changed(changes, n):
            if len(selected) == budget:
                break
            if i not in selected:
                selected.append(i)
        return sorted(selected)
    if method == 'scene':
        cuts = []
        for i in sorted(range(1, n), key=lambda i: (-changes[i], i)):
            if len(cuts) == budget - 1:
                break
            if all(abs(i - j) > 2 for j in cuts):
                cuts.append(i)
        # Very short inputs: fill boundaries deterministically to honor budget.
        for i in range(1, n):
            if len(cuts) == budget - 1:
                break
            if i not in cuts:
                cuts.append(i)
        boundaries = [0] + sorted(cuts) + [n]
        return [(a + b - 1) // 2 for a, b in zip(boundaries, boundaries[1:])]
    raise ValueError(f'Not a static selector: {method}')


def inside(t, intervals):
    return any(a <= t < b for a, b in intervals)


def evaluate_query(ranked, selected, intervals):
    if not ranked or not intervals:
        raise ValueError('Ranking and annotated intervals cannot be empty')
    return {
        'recall_at_1': int(inside(ranked[0], intervals)),
        'recall_at_3': int(any(inside(t, intervals) for t in ranked[:3])),
        'coverage': int(any(inside(t, intervals) for t in selected)),
        'localization_error_s': min(max(a - ranked[0], 0, ranked[0] - b) for a, b in intervals),
        'midpoint_error_s': min(abs(ranked[0] - (a + b) / 2) for a, b in intervals),
        'short_event': all(b - a <= 2.0 + 1e-9 for a, b in intervals),
    }


def quantile(values, p):
    if not values:
        return None
    values = sorted(values)
    position = (len(values) - 1) * p
    low, high = math.floor(position), math.ceil(position)
    return values[low] + (values[high] - values[low]) * (position - low)


def aggregate(rows):
    if not rows:
        raise ValueError('Cannot summarize empty results')
    short = [r for r in rows if r['metrics']['short_event']]
    result = {'queries': len(rows), 'short_queries': len(short)}
    for key in ('recall_at_1', 'recall_at_3', 'coverage'):
        result[key] = statistics.mean(r['metrics'][key] for r in rows)
    for k in (1, 3):
        result[f'short_recall_at_{k}'] = statistics.mean(r['metrics'][f'recall_at_{k}'] for r in short) if short else None
    for key in ('localization_error_s', 'midpoint_error_s'):
        values = [r['metrics'][key] for r in rows]
        result[f'{key}_median'] = statistics.median(values)
        result[f'{key}_p95'] = quantile(values, .95)
    if all('cost' in r for r in rows):
        for key in ('index_ms', 'query_ms', 'total_ms'):
            values = [r['cost'][key] for r in rows]
            result[f'{key}_median'] = statistics.median(values)
            result[f'{key}_p95'] = quantile(values, .95)
        result['image_calls_total'] = sum(r['cost']['image_calls'] for r in rows)
        result['text_calls_total'] = sum(r['cost']['text_calls'] for r in rows)
    return result


def summarize(rows):
    overall = {m: aggregate([r for r in rows if r['method'] == m]) for m in METHODS}
    groups = {}
    for field in ('clip_id', 'source_id'):
        groups[field] = {
            value: {m: aggregate([r for r in rows if r['method'] == m and r[field] == value]) for m in METHODS}
            for value in sorted({r[field] for r in rows})
        }
    return {'overall': overall, **groups}


def gate(summary):
    overall = summary['overall']
    h = overall['hierarchical']
    best = lambda key: max(overall[m][key] for m in BASELINES)
    enough = lambda value, threshold: value >= threshold - 1e-9
    checks = {
        'recall1_gain_10pp': enough(h['recall_at_1'] - best('recall_at_1'), .10),
        'recall3_gain_10pp': enough(h['recall_at_3'] - best('recall_at_3'), .10),
        'short_recall3_loss_at_most_5pp': enough(h['short_recall_at_3'] - best('short_recall_at_3'), -.05),
        'recall3_at_least_80pct': enough(h['recall_at_3'], .80),
        'median_localization_regression_at_most_half_second':
            h['localization_error_s_median'] <= min(overall[m]['localization_error_s_median'] for m in BASELINES) + .5 + 1e-9,
        'positive_gain_in_half_windows': sum(
            c['hierarchical']['recall_at_3'] > max(c[m]['recall_at_3'] for m in BASELINES) + 1e-9
            for c in summary['clip_id'].values()) >= math.ceil(len(summary['clip_id']) / 2),
        'neither_source_loses_over_5pp': all(
            enough(c['hierarchical']['recall_at_3'] - max(c[m]['recall_at_3'] for m in BASELINES), -.05)
            for c in summary['source_id'].values()),
    }
    simple = []
    for m in BASELINES:
        v = overall[m]
        if (enough(v['recall_at_1'], .6) and enough(v['recall_at_3'], .8)
                and enough(v['short_recall_at_3'], .6) and v['localization_error_s_median'] <= 1
                and all(enough(s[m]['recall_at_3'], .6) for s in summary['source_id'].values())):
            simple.append(m)
    return {
        'adaptive_verdict': 'provisionally_survives' if all(checks.values()) else 'kill_adaptive_v1',
        'checks': checks, 'simple_usefulness_gate_passes': simple,
        'competition_novelty_proven_by_simple_gate': False,
    }


def paired_bootstrap(rows, samples=2000):
    by_key = {(r['method'], r['clip_id'], r['query_id']): r for r in rows}
    clips = sorted({r['clip_id'] for r in rows})
    result = {}
    for m in BASELINES:
        result[m] = {}
        for metric in ('recall_at_1', 'recall_at_3'):
            deltas = {c: [] for c in clips}
            for r in rows:
                if r['method'] == 'hierarchical':
                    deltas[r['clip_id']].append(r['metrics'][metric] - by_key[(m, r['clip_id'], r['query_id'])]['metrics'][metric])
            flat = sum(deltas.values(), [])
            rng = random.Random(20260920)
            distribution = []
            for _ in range(samples):
                drawn = [v for c in rng.choices(clips, k=len(clips)) for v in deltas[c]]
                distribution.append(statistics.mean(drawn))
            result[m][metric] = {
                'hierarchical_minus_baseline': statistics.mean(flat),
                'wins': sum(v > 0 for v in flat), 'losses': sum(v < 0 for v in flat),
                'clip_cluster_bootstrap_95pct': [quantile(distribution, .025), quantile(distribution, .975)],
                'resamples': samples, 'seed': 20260920,
            }
    return result


def boundary_sensitivity(rows):
    """Secondary robustness diagnostic; never changes the locked primary gate."""
    reports = {}
    for margin in (-.25, .25):
        adjusted = []
        for row in rows:
            intervals = [[max(0, a - margin), b + margin] for a, b in row['intervals_s']]
            metrics = evaluate_query(row['ranked_times_s'], row['selected_times_s'], intervals)
            metrics['short_event'] = row['metrics']['short_event']  # fixed stratum
            adjusted.append({**row, 'metrics': metrics})
        summary = summarize(adjusted)
        reports['expanded_025s' if margin > 0 else 'eroded_025s'] = {
            'summary': summary, 'gate_diagnostic': gate(summary),
        }
    return reports
